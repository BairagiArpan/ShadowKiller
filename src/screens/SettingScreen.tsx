import React from 'react';
import { Pressable, ScrollView, StyleSheet, Text, View } from 'react-native';
import { NativeStackScreenProps } from '@react-navigation/native-stack';
import { RootStackParamList } from '../navigation/types';
import { useSave } from '../persistence/SaveProvider';
import { PRESETS, QUALITY_ORDER } from '../config/graphics';

type Props = NativeStackScreenProps<RootStackParamList, 'Settings'>;

function Chip({ label, on, onPress }: { label: string; on: boolean; onPress: () => void }) {
  return (
    <Pressable onPress={onPress} style={[styles.chip, on && styles.chipOn]}>
      <Text style={styles.chipTxt}>{label}</Text>
    </Pressable>
  );
}

export default function SettingsScreen({ navigation }: Props) {
  const { save, updateSettings } = useSave();
  const s = save.settings;
  const size = Math.round(s.controlSize * 100);
  const step = (d: number) => updateSettings({ controlSize: Math.round((s.controlSize + d) * 10) / 10 });

  return (
    <View style={styles.root}>
      <View style={styles.header}>
        <Pressable onPress={() => navigation.goBack()}><Text style={styles.back}>◀ BACK</Text></Pressable>
        <Text style={styles.title}>SETTINGS</Text>
        <View style={{ width: 60 }} />
      </View>
      <ScrollView contentContainerStyle={styles.body}>
        <Text style={styles.label}>AUDIO</Text>
        <View style={styles.row}>
          <Chip label={`Sound ${s.sound ? 'ON' : 'OFF'}`} on={s.sound} onPress={() => updateSettings({ sound: !s.sound })} />
          <Chip label={`Music ${s.music ? 'ON' : 'OFF'}`} on={s.music} onPress={() => updateSettings({ music: !s.music })} />
        </View>
            <Text style={styles.note}>Sound effects and music are generated by the game itself. No downloads needed.</Text>

        <Text style={styles.label}>GRAPHICS</Text>
        <View style={styles.row}>
          {QUALITY_ORDER.map((q) => (
            <Chip key={q} label={PRESETS[q].label} on={s.graphics === q} onPress={() => updateSettings({ graphics: q })} />
          ))}
        </View>
        <Text style={styles.note}>{PRESETS[s.graphics].description}</Text>
        <Text style={styles.note}>
          If the game runs slowly, it lowers the preset for that session only. Your saved choice stays as it is.
        </Text>

        <Text style={styles.label}>FRAME RATE</Text>
        <View style={styles.row}>
          <Chip label="30 FPS" on={s.fps === 30} onPress={() => updateSettings({ fps: 30 })} />
          <Chip label="60 FPS" on={s.fps === 60} onPress={() => updateSettings({ fps: 60 })} />
        </View>
        <Text style={styles.note}>Combat runs at the same speed either way. 30 FPS only draws less often to save battery and heat.</Text>

        <Text style={styles.label}>CONTROL SIZE</Text>
        <View style={styles.row}>
          <Chip label="−" on={false} onPress={() => step(-0.1)} />
          <View style={styles.value}><Text style={styles.chipTxt}>{size}%</Text></View>
          <Chip label="+" on={false} onPress={() => step(0.1)} />
        </View>

        <Text style={styles.label}>LANGUAGE</Text>
        <View style={styles.row}>
          <Chip label="English" on onPress={() => {}} />
        </View>
        <Text style={styles.note}>More languages need translated text. Only English exists so far.</Text>
      </ScrollView>
    </View>
  );
}

const styles = StyleSheet.create({
  root: { flex: 1, backgroundColor: '#0a0a14', paddingTop: 8 },
  header: { flexDirection: 'row', justifyContent: 'space-between', alignItems: 'center', paddingHorizontal: 20 },
  back: { color: '#bfa3ff', fontWeight: '800', width: 60 },
  title: { color: '#fff', fontWeight: '900', fontSize: 20, letterSpacing: 5 },
  body: { padding: 20, gap: 8 },
  label: { color: '#bfa3ff', fontWeight: '800', letterSpacing: 3, marginTop: 8 },
  row: { flexDirection: 'row', gap: 8, alignItems: 'center', flexWrap: 'wrap' },
  note: { color: '#9a9ab5', fontSize: 11 },
  chip: { backgroundColor: '#1a1a2e', paddingHorizontal: 18, paddingVertical: 8, borderRadius: 8, borderWidth: 2, borderColor: '#2a2a45' },
  chipOn: { backgroundColor: '#4b2fa8', borderColor: '#bfa3ff' },
  chipTxt: { color: '#fff', fontWeight: '800' },
  value: { paddingHorizontal: 14 },
});